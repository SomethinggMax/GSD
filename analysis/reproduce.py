"""Regenerates every table, figure and number of Section 7 of the paper from the raw data in
energy-bench/results/. Writes analysis/output/REPORT.md, output/tables/*.csv and output/figures/*.

    python analysis/reproduce.py
"""
import matplotlib

matplotlib.use("Agg")

import data_quality  # noqa: E402
import effective_b  # noqa: E402
import jfr_table  # noqa: E402
import rq1_baseline  # noqa: E402
import rq2_rq3  # noqa: E402
import rq4_rankings  # noqa: E402
from common import RUN_DIR, ROOT, out_path  # noqa: E402

SECTIONS = [data_quality, rq1_baseline, rq2_rq3, rq4_rankings, effective_b, jfr_table]


def main():
    parts = ["# Reproduced results", "",
             f"Generated by `analysis/reproduce.py` from `{RUN_DIR.relative_to(ROOT)}`. "
             "Section numbers follow the paper. Energy = RAPL package + DRAM; differences are relative to "
             "virtual threads (positive = more than VT).", ""]
    for section in SECTIONS:
        print(f"running {section.__name__} ...", flush=True)
        parts += [section.run(), ""]
    report = out_path("REPORT.md")
    report.write_text("\n".join(parts))
    print(f"done -> {report}")


if __name__ == "__main__":
    main()
